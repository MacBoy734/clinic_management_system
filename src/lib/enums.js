// Convert a kebab-case slug to a readable display name.
export function formatMedicationName(slug) {
  if (!slug) return ''
  return slug
    .split('-')
    .map((part) => {
      if (/^\d+$/.test(part)) return part
      return part.charAt(0).toUpperCase() + part.slice(1)
    })
    .join(' ')
}

export const MEDICATION_GENERIC_NAMES_DISPLAY = MEDICATION_GENERIC_NAMES.map(formatMedicationName)

